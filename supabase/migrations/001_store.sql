create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_store_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.admin_users where user_id = auth.uid()
  );
$$;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null check (category in ('Calzado Hombre', 'Calzado Mujer', 'Sandalias Tejidas', 'Carteras')),
  price numeric(10, 2) not null check (price > 0),
  badge text not null default '',
  badge_accent boolean not null default false,
  is_new boolean not null default true,
  popularity integer not null default 80,
  tags text not null default '',
  image text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.product_sizes (
  product_id bigint not null references public.products(id) on delete cascade,
  size text not null,
  stock integer not null default 0 check (stock >= 0),
  primary key (product_id, size)
);

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  phone text unique,
  address text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  order_code text primary key default ('TRZ-' || lpad(nextval('public.order_number_seq')::text, 6, '0')),
  customer_id uuid not null references public.customers(id),
  delivery_address text not null,
  channel text not null default 'WhatsApp',
  status text not null default 'Pendiente'
    check (status in ('Pendiente', 'Enviado', 'Entregado', 'Cancelado')),
  total numeric(10, 2) not null default 0 check (total >= 0),
  total_items integer not null default 0 check (total_items >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_code text not null references public.orders(order_code) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  size text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10, 2) not null check (unit_price >= 0),
  subtotal numeric(10, 2) not null check (subtotal >= 0)
);

create index if not exists orders_customer_id_idx on public.orders(customer_id);
create index if not exists order_items_order_code_idx on public.order_items(order_code);

